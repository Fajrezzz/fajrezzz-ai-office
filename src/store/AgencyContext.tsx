function nowClock(): string {
  return new Date().toLocaleTimeString("id-ID", {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  });
}

function makeLog(
  level: DivisionLogEntry["level"],
  message: string
): DivisionLogEntry {
  return { time: nowClock(), level, message };
}

